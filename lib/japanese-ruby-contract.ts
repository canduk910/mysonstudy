/** 후리가나 토큰 하나 — 표기(surface)와 그 위 독음(reading, 한자 포함 시에만). */
export interface JaToken {
  /** 원문 표기 조각(한자·가나·숫자·기호). 순서대로 이으면 원문과 같다 */
  surface: string;
  /** 히라가나 독음 — surface에 한자가 있을 때만. 없으면 null(루비를 달지 않는다) */
  reading: string | null;
}
